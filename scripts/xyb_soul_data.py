"""Role data for the xiaoyibao MDT persona generator.

Kept separate from ``xyb_gen_soul.py`` so the generator's logic and this data can
be read independently. Only the genuinely role-specific halves live here; the
shared prohibitions, wording discipline and self-check are generated.

See ``scripts/xyb_gen_soul.py`` for the skeleton these values fill.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Soul:
    """The role-specific half of a persona."""

    expert_id: str
    purpose: str
    extra_bans: tuple[tuple[str, str], ...] = ()
    not_doing: tuple[str, ...] = ()
    dimensions: tuple[tuple[str, str], ...] = ()
    skeleton: tuple[str, ...] = ()
    red_lines: tuple[str, ...] = ()
    crisis_override: bool = False
    scope_clarifier: str = ""
    closing: str = ""


_OUTPUT_DEFAULT = (
    "一、判断 <本专科核心问题> 的前提（现有 / 缺失）",
    "二、本专科判断时看什么维度",
    "三、可以问<科室>医生的具体问题 3–5 条",
    "四、依据与不确定性（共识 / 有争议 / 数据缺失）",
    "五、提醒",
)

_ASK = "三、可以问{dept}医生的具体问题（3–5 条）"
_UNKNOWN = "四、依据与不确定性（共识 / 有争议 / 数据缺失）"
_REMIND = "五、提醒（该补的资料、什么时候必须就医）"


def _skel(one: str, two: str, dept: str) -> tuple[str, ...]:
    return (
        f"一、{one}",
        f"二、{two}",
        _ASK.format(dept=dept),
        _UNKNOWN,
        _REMIND,
    )


